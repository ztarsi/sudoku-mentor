// Practice drills (#139) are the engine's own answers, and stay that way.
//
// A drill is a real position from a library puzzle's solve path on which a
// technique is present: the givens, and the board as the mentor's own steps
// left it, digits and pencil marks. practiceDrills.js is a cache of those
// positions, written by this test from the live engine and held to it by
// the same test, the pattern the library's labels use (#95). Every drill
// must still have its technique on its board, every instance there must
// agree with the puzzle's one answer, and a drill marked as the next step
// must still be what the hint gives there. A stale drill fails the build
// rather than misleading a player.
//
// To rewrite the drills after changing the engine or the library:
//   UPDATE_PRACTICE_DRILLS=1 npx vitest run src/components/sudoku/__tests__/practiceDrills.spec.js
import { describe, it, expect } from 'vitest';
import { PUZZLES } from '../puzzles';
import {
  findAllTechniqueInstances,
  findNextLogicStep,
  applyLogicStep,
  eliminateCandidatesFromPeers,
  generateCandidates,
} from '../logicEngine';
import { findWhatIfStep } from '../forcingChainEngine';
import { establishUniqueness } from '../uniqueness';
import { solveSudoku } from '../solver';
import { TECHNIQUES, COUNT_SEARCH } from '../techniqueCatalog';
import { encodeCells, decodeCells } from '../boardCode';
import { PRACTICE_DRILLS } from '../practiceDrills';
import { PRACTICE_INDEX } from '../practiceIndex';
import { SHELF_LABELS } from '../whereTaught';

const env = /** @type {any} */ (globalThis).process?.env ?? {};

/** How many positions a technique gets, from different puzzles where it can. */
const PER_TECHNIQUE = 3;

// Every technique a player can look for by eye: not the search tiers, whose
// proofs by cases are not a pattern to find (spec: out of scope).
const PRACTISED = TECHNIQUES.filter((t) => t.count !== COUNT_SEARCH).map((t) => t.name);

const library = Object.entries(PUZZLES).flatMap(([shelf, list]) => list.map((p) => ({ shelf, ...p })));

const givensGrid = (digits) =>
  digits.map((value, index) => ({
    cellIndex: index,
    value: value || null,
    isFixed: value !== 0,
    candidates: [],
    isHighlighted: false,
    highlightColor: null,
    isBaseCell: false,
    isTargetCell: false,
  }));

const js = (value) => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const HEADER = `// GENERATED by __tests__/practiceDrills.spec.js: do not edit by hand.
//
// Practice positions (#139): for each technique, real positions from the
// library's solve paths on which it is present, as the puzzle's givens and
// the board the mentor's own steps left (boardCode.js). \`next\` is true where
// the technique is also what the hint gives on that board. Loaded only when
// a player starts practising. The test re-checks every drill against the
// live engine; to rewrite this file:
//   UPDATE_PRACTICE_DRILLS=1 npx vitest run src/components/sudoku/__tests__/practiceDrills.spec.js

/** @type {Record<string, { puzzle: string, board: string, next: boolean, from: string }[]>} */`;

const INDEX_HEADER = `// GENERATED by __tests__/practiceDrills.spec.js: do not edit by hand.
//
// How many practice positions each technique has (#139), so a technique's
// reference can offer practice without loading the positions themselves.

/** @type {Record<string, number>} */`;

describe('practice drills', () => {
  if (env.UPDATE_PRACTICE_DRILLS === '1') {
    it('rewrites the drills from the live engine', async () => {
      /** @type {Map<string, { puzzle: string, board: string, next: boolean, from: string }[]>} */
      const found = new Map(PRACTISED.map((name) => [name, []]));
      // Enough of a technique: PER_TECHNIQUE positions, each the next step,
      // each from a different puzzle. Until then it is still looked for.
      const settled = (name) => {
        const list = found.get(name);
        return list.length >= PER_TECHNIQUE && list.every((d) => d.next);
      };
      const offer = (name, drill) => {
        const list = found.get(name);
        const same = list.findIndex((d) => d.puzzle === drill.puzzle);
        if (same >= 0) {
          // One position per puzzle: a later one replaces it only by being
          // the next step where the first was not.
          if (!list[same].next && drill.next) list[same] = drill;
          return;
        }
        if (list.length < PER_TECHNIQUE) {
          list.push(drill);
          return;
        }
        // Full: a next-step drill displaces one that is not.
        const weaker = list.findIndex((d) => !d.next);
        if (drill.next && weaker >= 0) list[weaker] = drill;
      };

      for (const { shelf, name, puzzle } of library) {
        const key = puzzle.join('');
        const { state: uniqueness } = establishUniqueness(puzzle);
        let grid = generateCandidates(givensGrid(puzzle));
        for (let n = 0; n < 300; n++) {
          if (grid.every((c) => c.value !== null)) break;
          let step = findNextLogicStep(grid, null, { uniqueness });
          const board = encodeCells(grid);
          for (const technique of PRACTISED) {
            if (settled(technique)) continue;
            if (findAllTechniqueInstances(grid, technique, { uniqueness }).length === 0) continue;
            offer(technique, { puzzle: key, board, next: step?.technique === technique, from: `${SHELF_LABELS[shelf]}: ${name}` });
          }
          if (!step) step = findWhatIfStep(grid);
          if (!step) break;
          grid = applyLogicStep(grid, step);
          if (step.placement) grid = eliminateCandidatesFromPeers(grid, step.placement.cell, step.placement.digit);
        }
      }

      const lines = [];
      const index = [];
      for (const name of PRACTISED) {
        const drills = found.get(name).sort((a, b) => Number(b.next) - Number(a.next));
        if (drills.length === 0) continue;
        index.push(`  ${js(name)}: ${drills.length},`);
        lines.push(`  ${js(name)}: [`);
        for (const d of drills) {
          lines.push(`    { puzzle: ${js(d.puzzle)}, next: ${d.next}, from: ${js(d.from)},`);
          lines.push(`      board: ${js(d.board)} },`);
        }
        lines.push('  ],');
      }
      const { writeFileSync } = await import(['node', 'fs'].join(':'));
      writeFileSync(new URL('../practiceDrills.js', import.meta.url), `${HEADER}\nexport const PRACTICE_DRILLS = {\n${lines.join('\n')}\n};\n`);
      writeFileSync(new URL('../practiceIndex.js', import.meta.url), `${INDEX_HEADER}\nexport const PRACTICE_INDEX = {\n${index.join('\n')}\n};\n`);
    }, 3_600_000);
    return;
  }

  it('the index says exactly what the drills hold', () => {
    const counts = Object.fromEntries(Object.entries(PRACTICE_DRILLS).map(([name, list]) => [name, list.length]));
    expect(PRACTICE_INDEX).toEqual(counts);
  });

  it('offers only techniques a player can look for by eye', () => {
    for (const name of Object.keys(PRACTICE_DRILLS)) expect(PRACTISED, name).toContain(name);
  });

  // The spec's measure: the seven techniques the hint never reaches (#88)
  // each have practice positions, which is the point of practice.
  it('has positions for the techniques the hint never reaches', () => {
    for (const name of ['Remote Pairs', 'BUG+1', 'BUG+2', 'BUG+3', 'Mutant Fish', 'Continuous Loop']) {
      expect(PRACTICE_DRILLS[name]?.length ?? 0, name).toBeGreaterThan(0);
    }
  });

  for (const [technique, drills] of Object.entries(PRACTICE_DRILLS)) {
    it(`${technique}: every position still holds it, and it agrees with the answer`, () => {
      for (const drill of drills) {
        const digits = [...drill.puzzle].map(Number);
        const givens = givensGrid(digits);
        const grid = decodeCells(drill.board, givens);
        expect(grid, `${drill.from}: the board does not fit its givens`).not.toBeNull();
        const solution = solveSudoku(givens);
        const { state: uniqueness } = establishUniqueness(digits);
        const instances = findAllTechniqueInstances(grid, technique, { uniqueness });
        expect(instances.length, `${drill.from}: no ${technique} on this board any more`).toBeGreaterThan(0);
        for (const step of instances) {
          if (step.placement) expect(step.placement.digit).toBe(solution[step.placement.cell].value);
          for (const e of step.eliminations ?? []) expect(e.digit, `${drill.from}`).not.toBe(solution[e.cell].value);
        }
        if (drill.next) {
          expect(findNextLogicStep(grid, null, { uniqueness })?.technique, `${drill.from}: no longer the next step`).toBe(technique);
        }
      }
    });
  }
});
