// The library's precomputed answers (#95, #88) can never go stale quietly.
//
// The library shows what each built-in puzzle teaches from
// libraryTeaching.js instead of re-walking every solve path on every visit,
// and each technique's reference says which puzzles teach it from the same
// file. That file is a cache of the analyser's answers, and this test is
// what keeps it one: every built-in puzzle is re-measured with the live
// analyser and must match its entry exactly, every puzzle must have an
// entry, and there must be no entry for a puzzle the library no longer has.
// A measured label that nothing re-measures is a hand-written label again,
// which is the thing #71 removed.
//
// To rewrite the file from the live analyser after changing the library:
//   UPDATE_LIBRARY_TEACHING=1 npx vitest run src/components/sudoku/__tests__/libraryTeaching.spec.js
import { describe, it, expect } from 'vitest';
import { PUZZLES } from '../puzzles';
import { analyzePuzzle, analyzeSolvePath, teachingLabel } from '../difficultyAnalyzer';
import { teachingRank } from '../techniqueCatalog';
import { LIBRARY_TEACHING } from '../libraryTeaching';

const env = /** @type {any} */ (globalThis).process?.env ?? {};

// The generated file's header, written by the update mode below.
const HEADER = `// GENERATED by __tests__/libraryTeaching.spec.js: do not edit by hand.
//
// What each built-in library puzzle teaches, measured once rather than on
// every visit to the library (#95), and every technique its hint path uses,
// so a technique's reference can say where to meet it (#88). The library
// used to walk every solve path each time it opened; the Ultimate shelf
// alone took 13 seconds to fill in its labels.
//
// These are the analyser's own answers, not hand-written labels: the test
// re-measures every built-in puzzle with the live analyser and fails if any
// entry differs, if a library puzzle has no entry, or if an entry names a
// puzzle the library no longer has. That test is the feature; this file is
// only its cache. To rewrite it after changing the library:
//   UPDATE_LIBRARY_TEACHING=1 npx vitest run src/components/sudoku/__tests__/libraryTeaching.spec.js
//
// Keyed by the puzzle's 81 digits, so a puzzle keeps its entry through a
// rename. Imported and photographed puzzles are not here and are measured
// live, as before.

/** @type {Record<string, { complete: boolean, namedOnly: boolean, hardestTechnique: string | null, hardestTier: string | null, teaches: string[] }>} */`;
const library = Object.entries(PUZZLES).flatMap(([shelf, list]) => list.map((p) => ({ shelf, ...p })));

// What the library needs to know about a puzzle, measured now. `teaches` is
// every technique its hint path uses, in ladder order: the same walk the
// coverage report counts (whatIf: true).
const live = (puzzle) => {
  const a = analyzePuzzle(puzzle);
  const teaches = [...new Set(analyzeSolvePath(puzzle, { whatIf: true }).steps.map((s) => s.technique))].sort(
    (x, y) => teachingRank(x) - teachingRank(y) || x.localeCompare(y)
  );
  return { complete: a.complete, namedOnly: a.namedOnly, hardestTechnique: a.hardestTechnique, hardestTier: a.hardestTier, teaches };
};
// A JavaScript string literal in single quotes, escaped, so a name with an
// apostrophe in it cannot break the generated file.
const js = (value) => (value === null ? 'null' : `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`);
const asEntry = (key, e) =>
  `'${key}': { complete: ${e.complete}, namedOnly: ${e.namedOnly}, hardestTechnique: ${js(e.hardestTechnique)}, ` +
  `hardestTier: ${js(e.hardestTier)}, teaches: [${e.teaches.map(js).join(',')}] },`;

describe('the library labels are the live analyser\'s', () => {
  if (env.UPDATE_LIBRARY_TEACHING === '1') {
    it('rewrites libraryTeaching.js from the live analyser', async () => {
      // Node's fs, named indirectly: the typecheck covers browser code and
      // has no Node types, and only this update mode needs it.
      const { writeFileSync } = await import(['node', 'fs'].join(':'));
      const lines = library.map(({ shelf, name, puzzle }) => `  // ${shelf}: ${name}\n  ${asEntry(puzzle.join(''), live(puzzle))}`);
      const text = `${HEADER}\nexport const LIBRARY_TEACHING = {\n${lines.join('\n')}\n};\n`;
      writeFileSync(new URL('../libraryTeaching.js', import.meta.url), text);
    }, 600_000);
    return;
  }

  it('has an entry for every built-in puzzle, and none for a puzzle it no longer has', () => {
    const keys = new Set(library.map((p) => p.puzzle.join('')));
    for (const p of library) expect(LIBRARY_TEACHING[p.puzzle.join('')], `${p.shelf}: ${p.name} has no entry`).toBeDefined();
    for (const key of Object.keys(LIBRARY_TEACHING)) expect(keys.has(key), `an entry for a puzzle not in the library: ${key}`).toBe(true);
  });

  for (const { shelf, name, puzzle } of library) {
    it(`${shelf}: ${name} says what the analyser measures`, () => {
      const key = puzzle.join('');
      const measured = live(puzzle);
      expect(
        LIBRARY_TEACHING[key],
        `${name}: the precomputed entry is stale. Rewrite the file (see the top of this test), or replace the entry with:\n  ${asEntry(key, measured)}`
      ).toEqual(measured);
      // And so the row reads exactly what a live measurement would print.
      expect(teachingLabel(LIBRARY_TEACHING[key])).toBe(teachingLabel(analyzePuzzle(puzzle)));
    });
  }
});
